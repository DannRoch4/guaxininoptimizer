def cat_text(category: dict, field: str) -> str:
    """field: 'name' ou 'description'. Cai para o texto em categories.py (PT) se nao houver traducao."""
    lang = _current
    if lang == "pt":
        return category[field]
    entry = CATEGORY_I18N.get(lang, {}).get(category["id"])
    if not entry:
        return category[field]
    name, desc = entry
    return name if field == "name" else desc
